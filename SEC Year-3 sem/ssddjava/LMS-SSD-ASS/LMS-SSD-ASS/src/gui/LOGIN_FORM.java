    private void LOGIN_BUTTONActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_LOGIN_BUTTONActionPerformed
        String pwd = new String(pass.getPassword());
        String username = user.getText().trim();
        try {
            Validator.requireNonEmpty(username, "Username");
            Validator.requireNonEmpty(pwd, "Password");

            User authenticated = userDAO.findByUsernameAndPassword(username, pwd);
            if (authenticated != null) {
                JOptionPane.showMessageDialog(this, "Successfully login");
                this.setVisible(false);
                new HOME().setVisible(true);
                pass.setText("");
                user.setText("");
            } else {
                JOptionPane.showMessageDialog(this, "Enter valid username and password");
                pass.setText("");
                user.setText("");
            }
        } catch (InvalidInputException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Login failed: " + ex.getMessage());
        }
        
    }//GEN-LAST:event_LOGIN_BUTTONActionPerformed

